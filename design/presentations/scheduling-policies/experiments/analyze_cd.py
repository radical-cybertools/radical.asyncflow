"""Tables and charts for diagnostics C (raw Batch chain) and D (V1-style launch cost).

Usage: python analyze_cd.py <results/r3>

Reads ``chain/chain_*.json`` (diag_chain.py) and ``launch/launch_*.json`` (diag_launch.py),
writes ``chain/summary.md``, ``launch/summary.md`` and the charts ``r3_chain_edge`` and
``r3_launch`` (PDF and PNG) in ``<results/r3>``.
"""

import glob
import json
import os
import statistics
import sys

import analyze as a1

VARIANTS = {"seq": "Sequential (client round trip)", "ahead1": "Ahead, one compile",
            "aheadN": "Ahead, one compile per task"}
KINDS = {"func": "Function, trivial", "func_1s": "Function, sleep 1 s",
         "exe_true": "Executable, /bin/true", "exe_sleep1": "Executable, sleep 1"}


def mmm(xs):
    return a1.mmm(xs)


def chain(r3):
    rows = {}
    for p in sorted(glob.glob(os.path.join(r3, "chain", "chain_*.json"))):
        d = json.load(open(p))
        dragon = "branch (b)" if d["batch_kwargs"] else "stock 0.14.1"
        for r in d["runs"]:
            rows.setdefault((dragon, r["payload_bytes"], r["variant"]), []).append(dict(r, job=d["slurm_job_id"]))
    out = []
    for k in sorted(rows, key=lambda k: (k[0] != "stock 0.14.1", k[1], list(VARIANTS).index(k[2]))):
        rs = rows[k]
        warm = [r for r in rs if r["chain"] > 2]
        out.append({
            "key": k, "chains": len(rs), "jobs": sorted({r["job"] for r in rs}),
            "gap_p50": mmm([r["gap_ms"]["p50"] for r in rs]),
            "gap_p95": mmm([r["gap_ms"]["p95"] for r in rs]),
            "gap_p95_warm": mmm([r["gap_ms"]["p95"] for r in warm]),
            "gap_max": max(r["gap_ms"]["max"] for r in rs),
            "total_ms": mmm([r["total_s"] * 1e3 for r in rs]),
            "total_ms_warm": mmm([r["total_s"] * 1e3 for r in warm]),
            "first_start_ms": mmm([r["submit_to_first_start_ms"] for r in rs]),
            "max_submit_gap_ms": max(r["max_submit_gap_ms"] for r in rs),
            "finals": sorted({r["final_value"] for r in rs}),
        })
    return out


def busy(raw, k, warm=5):
    rows = sorted([r for r in raw if r.get("seen") is not None], key=lambda r: r["seen"])[warm:]
    if len(rows) < 2:
        return None
    span = max(r["t1"] for r in rows) - min(r["t0"] for r in rows)
    return 100.0 * sum(r["t1"] - r["t0"] for r in rows) / (k * span) if span > 0 else None


def launch(r3):
    rows = {}
    for p in sorted(glob.glob(os.path.join(r3, "launch", "launch_*.json"))):
        d = json.load(open(p))
        for c in d["configs"]:
            rows.setdefault((c["kind"], d["mode"], c["inflight"]), []).append(dict(c, job=d["slurm_job_id"]))
    out = []
    for k in sorted(rows, key=lambda k: (list(KINDS).index(k[0]), k[1] != "v1", k[2])):
        cs = rows[k]

        def m(key, sub="p50"):
            return mmm([(c.get(key) or {}).get(sub) for c in cs])

        out.append({
            "key": k, "runs": len(cs), "jobs": sorted(c["job"] for c in cs),
            "tasks": sum(c["tasks"] for c in cs), "failures": sum(c["failures"] for c in cs),
            "errors": [c["error"] for c in cs if c.get("error")],
            "left_alive": sum(c.get("left_alive") or 0 for c in cs),
            "cold_launch_ms": mmm([c["cold_launch_ms"] for c in cs]),
            "launch_p50": m("launch_ms"), "launch_p95": m("launch_ms", "p95"), "launch_max": m("launch_ms", "max"),
            "report_p50": m("report_ms"), "report_p95": m("report_ms", "p95"),
            "start_block_p50": m("start_block_ms"), "start_block_p95": m("start_block_ms", "p95"),
            "tasks_per_s": mmm([c.get("tasks_per_s") for c in cs]),
            "busy_pct": mmm([busy(c["raw"], k[2]) for c in cs]),
        })
    return out


def write_md(c, d, r3):
    f = a1.fmt
    L = ["# Diagnostic C: a chain of 100 trivial tasks in raw Batch (julia, 32 workers)\n",
         "Generated by `experiments/analyze_cd.py`. Median [min–max] over chains (5 per job, 3 jobs). "
         "Gap: end of task i to start of task i+1, inside the workers. 'Warm': chains 3–5 of each job.\n",
         "| Dragon | Payload | Variant | Chains | Gap p50 | Gap p95 | Gap p95, warm | Gap max | Chain total | "
         "Chain total, warm | Submit to task 1 start | Largest gap between submissions | Final value | Jobs |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in c:
        dr, pay, v = r["key"]
        L.append(f"| {dr} | {'1 MiB' if pay else 'none'} | {VARIANTS[v]} | {r['chains']} | "
                 f"{f(r['gap_p50'], digits=2, unit=' ms')} | {f(r['gap_p95'], digits=1, unit=' ms')} | "
                 f"{f(r['gap_p95_warm'], digits=1, unit=' ms')} | {r['gap_max']:.0f} ms | "
                 f"{f(r['total_ms'], digits=0, unit=' ms')} | {f(r['total_ms_warm'], digits=0, unit=' ms')} | "
                 f"{f(r['first_start_ms'], digits=1, unit=' ms')} | "
                 f"{'–' if v == 'seq' else format(r['max_submit_gap_ms'], '.2f') + ' ms'} | "
                 f"{', '.join(map(str, r['finals']))} | {', '.join(r['jobs'])} |")
    L.append("\nThe first task returns 0, so a chain of 100 ends at 99.")
    open(os.path.join(r3, "chain", "summary.md"), "w").write("\n".join(L) + "\n")
    L = ["# Diagnostic D: V1-style launch (one Dragon process per task) vs Batch (julia)\n",
         "Generated by `experiments/analyze_cd.py`. Median [min–max] over 3 jobs of each statistic. The first 5 "
         "tasks of each configuration are left out; cold = the very first task. Busy: body time ÷ (in flight × "
         "span of those bodies).\n"]
    for kind, title in KINDS.items():
        L += [f"## {title}\n",
              "| Launcher | In flight | Tasks | Cold launch | Launch p50 | Launch p95 | Report p50 | Report p95 | "
              "start() blocks, p50 | Tasks/s | Busy | Failures | Left alive | Jobs |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in d:
            k, mode, n = r["key"]
            if k != kind:
                continue
            L.append(f"| {'V1 Process' if mode == 'v1' else 'Batch (a)+(b)'} | {n} | {r['tasks']} | "
                     f"{f(r['cold_launch_ms'], digits=0, unit=' ms')} | {f(r['launch_p50'], digits=1, unit=' ms')} | "
                     f"{f(r['launch_p95'], digits=1, unit=' ms')} | {f(r['report_p50'], digits=1, unit=' ms')} | "
                     f"{f(r['report_p95'], digits=1, unit=' ms')} | "
                     f"{f(r['start_block_p50'], digits=1, unit=' ms') if mode == 'v1' else '–'} | "
                     f"{f(r['tasks_per_s'], digits=1)} | {f(r['busy_pct'], digits=0, unit='%') if '1' in kind else '–'} | "
                     f"{r['failures']}{' (' + '; '.join(r['errors']) + ')' if r['errors'] else ''} | "
                     f"{r['left_alive'] if mode == 'v1' else '–'} | {', '.join(r['jobs'])} |")
        L.append("")
    open(os.path.join(r3, "launch", "summary.md"), "w").write("\n".join(L) + "\n")
    json.dump({"chain": c, "launch": d}, open(os.path.join(r3, "summary_cd.json"), "w"), indent=1, default=str)


def charts(c, d, r3):
    plt = a1.setup_mpl()
    rows = [r for r in c if r["key"][1] == 0]
    fig, ax = plt.subplots(figsize=(7.2, 3.0))
    colors = {"stock 0.14.1": a1.GRAY, "branch (b)": a1.ORANGE}
    labels = []
    for i, v in enumerate(VARIANTS):
        for j, dr in enumerate(colors):
            r = next(x for x in rows if x["key"][0] == dr and x["key"][2] == v)
            y = i + (j - 0.5) * 0.38
            s = r["gap_p50"]
            ax.barh(y, s["median"], height=0.34, color=colors[dr], label=dr if i == 0 else None)
            ax.plot([s["min"], s["max"]], [y, y], color=a1.INK, linewidth=1.0)
            ax.text(s["max"] + 0.15, y, f"{s['median']:.1f} ms", va="center", fontsize=8.5, color=a1.INK)
        labels.append(VARIANTS[v])
    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels, fontsize=9.5, color=a1.INK)
    ax.invert_yaxis()
    ax.set_xlim(0, 13)
    ax.set_xlabel("gap from one task's end to the next one's start, p50 of a chain (median of 15 chains)")
    ax.set_axisbelow(True)
    ax.set_title("Diagnostic C: Dragon's own dependency edge, raw Batch", loc="left", fontsize=12, color=a1.INK,
                 pad=31)
    ax.legend(loc="lower left", bbox_to_anchor=(0, 1.0), ncol=2, fontsize=9.5, borderaxespad=0.2, handlelength=1.2)
    a1.save(fig, r3, "r3_chain_edge")
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(11.5, 3.6))
    for ax, (key, title, xlab) in zip(axes, (("launch_p50", "Launch latency, p50", "ms, submit or start() to "
                                              "body's first line"),
                                             ("tasks_per_s", "Throughput, trivial tasks", "tasks per second"))):
        sel = [r for r in d if r["key"][0] in ("func", "exe_true")]
        names = []
        for i, r in enumerate(sel):
            s = r[key]
            if s is None:
                continue
            kind, mode, n = r["key"]
            color = a1.BLUE if kind == "func" else "#1baf7a"
            ax.barh(i, s["median"], height=0.7, color=color,
                    label=("function" if kind == "func" else "executable") if (mode, n) == ("v1", 1) else None)
            ax.plot([s["min"], s["max"]], [i, i], color=a1.INK, linewidth=1.0)
            ax.text(s["max"], i, f"  {s['median']:.0f}", va="center", fontsize=8.5, color=a1.INK)
            names.append(f"{'V1' if mode == 'v1' else 'Batch'} ×{n} · {'func' if kind == 'func' else 'exe'}")
        ax.set_yticks(range(len(names)))
        ax.set_yticklabels(names, fontsize=9, color=a1.INK)
        ax.invert_yaxis()
        ax.set_xlim(0, ax.get_xlim()[1] * 1.15)
        ax.set_xlabel(xlab)
        ax.set_title(title, loc="left", fontsize=10.5, color=a1.INK)
        ax.set_axisbelow(True)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.suptitle("Diagnostic D: one Dragon process per task (V1) against Batch, trivial tasks (median of 3 jobs)",
                 x=0.01, ha="left", fontsize=12, color=a1.INK)
    fig.tight_layout()
    fig.legend(handles, labels, loc="upper center", ncol=2, fontsize=9.5, frameon=False, bbox_to_anchor=(0.5, 0.0))
    a1.save(fig, r3, "r3_launch")
    plt.close(fig)


def main():
    r3 = sys.argv[1]
    c, d = chain(r3), launch(r3)
    write_md(c, d, r3)
    charts(c, d, r3)
    print(open(os.path.join(r3, "chain", "summary.md")).read())
    print(open(os.path.join(r3, "launch", "summary.md")).read())


if __name__ == "__main__":
    main()
